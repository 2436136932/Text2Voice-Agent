/** Base URL of the backend API, e.g. `/api/v1`. */
export const API_BASE_URL: string = import.meta.env.VITE_API_BASE_URL || '/api/v1'

export const http: AxiosInstance = axios.create({
  baseURL: API_BASE_URL,
  timeout: DEFAULT_REQUEST_TIMEOUT_MS,
  // Note: no default Content-Type here on purpose. A per-instance JSON default
  // would be inherited by FormData requests and suppress the multipart
  // boundary; the request interceptor sets JSON only when appropriate.
  headers: {
    Accept: 'application/json',
  },
})

http.interceptors.request.use((config: InternalAxiosRequestConfig) => {
  config.timeout = getRequestTimeout()
  const headers = AxiosHeaders.from(config.headers as never)
  if (!headers.get('X-Request-ID')) {
    headers.set('X-Request-ID', createRequestId())
  }
  // Only default the content type for JSON bodies. A FormData upload must keep
  // the browser-generated `multipart/form-data; boundary=...` header — forcing
  // JSON here silently broke every file upload (the body was serialised as
  // JSON, so the server never saw the file field).
  const isFormData =
    typeof FormData !== 'undefined' && config.data instanceof FormData
  if (!isFormData) {
    headers.set('Content-Type', 'application/json')
  }
  config.headers = headers
  return config
})

http.interceptors.response.use(
  (response: AxiosResponse) => response,
  (error: unknown) => Promise.reject(toApiError(error)),
)

/**
 * Perform a request and return only the response body.
 * Failures are always thrown as {@link ApiError}.
 */
export async function request<T>(config: Parameters<AxiosInstance['request']>[0]): Promise<T> {
  try {
    const response = await http.request<T>(config)
    return response.data
  } catch (error) {
    throw toApiError(error)
  }
}

/** Convenience wrapper around {@link request} for GET calls. */
export function get<T>(url: string, params?: Record<string, unknown>): Promise<T> {
  return request<T>({ method: 'GET', url, params })
}

/** Convenience wrapper around {@link request} for POST calls. */
export function post<T>(url: string, data?: unknown): Promise<T> {
  return request<T>({ method: 'POST', url, data })
}

/** Convenience wrapper around {@link request} for PUT calls. */
export function put<T>(url: string, data?: unknown): Promise<T> {
  return request<T>({ method: 'PUT', url, data })
}

/** Convenience wrapper around {@link request} for DELETE calls. */
export function del<T>(url: string, data?: unknown): Promise<T> {
  return request<T>({ method: 'DELETE', url, data })
}

export default http