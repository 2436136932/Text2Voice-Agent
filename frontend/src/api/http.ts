/* ------------------------------------------------------------------ */
/* Timeout configuration                                               */
/* ------------------------------------------------------------------ */

/** Default request timeout in milliseconds (matches the backend default). */
export const DEFAULT_REQUEST_TIMEOUT_MS = 120_000

let requestTimeoutMs = DEFAULT_REQUEST_TIMEOUT_MS

/**
 * Set the timeout applied to every outgoing request.
 *
 * Called by the settings store once `GET /settings` resolves (and after every
 * successful `PUT /settings`), so the axios instance always mirrors
 * `request_timeout_seconds`. Keeping it as a module-level setter avoids a
 * circular import between the HTTP layer and the Pinia stores.
 */
export function setRequestTimeout(ms: number | null | undefined): void {
  const next = Number(ms)
  requestTimeoutMs = Number.isFinite(next) && next > 0 ? next : DEFAULT_REQUEST_TIMEOUT_MS
}

/** Current request timeout in milliseconds. */
export function getRequestTimeout(): number {
  return requestTimeoutMs
}

/** Convert backend `request_timeout_seconds` into milliseconds. */
export function secondsToTimeoutMs(seconds: number | null | undefined): number {
  const value = Number(seconds)
  return Number.isFinite(value) && value > 0 ? value * 1000 : DEFAULT_REQUEST_TIMEOUT_MS
}

/* ------------------------------------------------------------------ */
/* ApiError                                                            */
/* ------------------------------------------------------------------ */

/**
 * Normalised error thrown by every request helper in `src/api`.
 *
 * The backend always answers failures with the envelope
 * `{ code, message, detail, request_id }`; anything else (transport failure,
 * timeout, unparsable body) is mapped to `NETWORK_ERROR`, `REQUEST_TIMEOUT` or
 * `HTTP_<status>`.
 */
export class ApiError extends Error {
  /** Machine-readable code, e.g. `TTS_AUTH_FAILED`. */
  readonly code: string
  /** Human readable message from the backend (Chinese or English). */
  override readonly message: string
  /** Optional structured context, never contains credentials. */
  readonly detail: Record<string, unknown> | null
  /** Correlation id echoed by the backend (or generated by this client). */
  readonly requestId: string | null
  /** HTTP status code, or `null` for transport-level failures. */
  readonly status: number | null
  /** `true` when the request never produced an HTTP response. */
  readonly isNetworkError: boolean
  /** `true` when the request was aborted by the client timeout. */
  readonly isTimeout: boolean

  constructor(init: {
    code: string
    message: string
    detail?: Record<string, unknown> | null
    requestId?: string | null
    status?: number | null
    isNetworkError?: boolean
    isTimeout?: boolean
  }) {
    super(init.message)
    this.name = 'ApiError'
    this.code = init.code
    this.message = init.message
    this.detail = init.detail ?? null
    this.requestId = init.requestId ?? null
    this.status = init.status ?? null
    this.isNetworkError = init.isNetworkError ?? false
    this.isTimeout = init.isTimeout ?? false
    // Restore the prototype chain when targeting ES5-ish output.
    Object.setPrototypeOf(this, ApiError.prototype)
  }

  /** Rebuild the backend envelope shape for display purposes. */
  toEnvelope(): ApiErrorEnvelope {
    return {
      code: this.code,
      message: this.message,
      detail: this.detail,
      request_id: this.requestId,
    }
  }
}

/** Type guard for {@link ApiError}. */
export function isApiError(value: unknown): value is ApiError {
  return value instanceof ApiError
}

/** Whether an error carries the given backend error code. */
export function isApiErrorCode(value: unknown, code: string): boolean {
  return isApiError(value) && value.code === code
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/** Read the `X-Request-ID` response header (or the request one) as a fallback. */
function readRequestId(error: AxiosError): string | null {
  const responseHeaders = error.response?.headers
  if (responseHeaders) {
    const value = AxiosHeaders.from(responseHeaders as never).get('x-request-id')
    if (typeof value === 'string' && value.length > 0) return value
  }
  const requestHeaders = error.config?.headers
  if (requestHeaders) {
    const value = AxiosHeaders.from(requestHeaders as never).get('X-Request-ID')
    if (typeof value === 'string' && value.length > 0) return value
  }
  return null
}

/** Map any thrown value onto an {@link ApiError}. */
export function toApiError(value: unknown): ApiError {
  if (isApiError(value)) return value

  if (axios.isAxiosError(value)) {
    const error = value as AxiosError
    const status = error.response?.status ?? null
    const requestId = readRequestId(error)
    const payload: unknown = error.response?.data

    // 1. The documented error envelope.
    if (isRecord(payload) && typeof payload.message === 'string') {
      return new ApiError({
        code: typeof payload.code === 'string' && payload.code ? payload.code : `HTTP_${status ?? 0}`,
        message: payload.message,
        detail: isRecord(payload.detail) ? payload.detail : null,
        requestId:
          typeof payload.request_id === 'string' && payload.request_id ? payload.request_id : requestId,
        status,
      })
    }

    // 2. Client-side timeout (axios uses ECONNABORTED / ETIMEDOUT).
    if (error.code === AxiosError.ECONNABORTED || error.code === AxiosError.ETIMEDOUT) {
      return new ApiError({
        code: 'REQUEST_TIMEOUT',
        message: `请求超时（超过 ${Math.round(requestTimeoutMs / 1000)} 秒未响应），请稍后重试或调高超时时间。`,
        requestId,
        status,
        isTimeout: true,
      })
    }

    // 3. No response at all: network / CORS / backend down.
    if (!error.response) {
      return new ApiError({
        code: 'NETWORK_ERROR',
        message: '无法连接到后端服务，请确认服务已启动且网络可达。',
        requestId,
        status: null,
        isNetworkError: true,
      })
    }

    // 4. Non-2xx without a parsable envelope.
    return new ApiError({
      code: `HTTP_${status}`,
      message:
        typeof payload === 'string' && payload.trim().length > 0
          ? payload.slice(0, 500)
          : `请求失败（HTTP ${status}）`,
      requestId,
      status,
    })
  }

  if (value instanceof Error) {
    return new ApiError({ code: 'UNKNOWN_ERROR', message: value.message || '未知错误' })
  }

  return new ApiError({ code: 'UNKNOWN_ERROR', message: '未知错误' })
}

